"""Типизированные ошибки интерфейсов хранилищ. Вызывающий код ловит именно их, а не голое исключение."""


class SheetsError(Exception):
    """Чтение или запись Google Таблиц не удались либо запись отклонена (сдвиг строк, неверный лист)."""


class CrmError(Exception):
    """Вызов Bitrix24 не удался."""
